require('./test-display.cjs').install()
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { _electron: electron } = require('playwright')

async function main() {
  const output = path.resolve('output/playwright/team-model-management')
  await fs.mkdir(output, { recursive: true })
  const profile = await fs.mkdtemp(path.join(output, 'profile-')), parent = await fs.mkdtemp(path.join(output, 'projects-'))
  const env = { ...process.env, COPROJER_USER_DATA: profile }
  delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL
  let app, page
  const errors = [], screenshots = []
  const invoke = (method, ...args) => page.evaluate(({ method, args }) => window.desktop.engineering[method](...args), { method, args })
  const state = () => invoke('state')
  async function launch() {
    app = await electron.launch({ args: ['.', '--disable-gpu'], env, cwd: process.cwd() })
    page = await app.firstWindow(); page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(error.message))
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.getByRole('heading', { name: '项目管理', exact: true }).waitFor()
    const display = await app.evaluate(() => global.__coprojerTestDisplay)
    assert.ok(display.windows.every(w => !w.initiallyVisible && w.displayId === display.selection.targetId))
    console.log('Display:', JSON.stringify(display.selection))
  }
  async function capture(name, width, height, theme = 'light') {
    await app.evaluate(({ BrowserWindow }, size) => { const w = BrowserWindow.getAllWindows()[0]; w.unmaximize(); w.setMinimumSize(1, 1); w.setContentSize(size.width, size.height) }, { width, height })
    await page.waitForFunction(({ width, height }) => innerWidth === width && innerHeight === height, { width, height })
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'window overflow')
    for (const dialog of await page.locator('dialog[open]').all()) assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'dialog overflow')
    const file = path.join(output, `${name}-${width}-${theme}.png`)
    await page.screenshot({ path: file, animations: 'disabled', scale: 'css' }); screenshots.push(file)
  }
  try {
    await launch()
    const model = { name: 'fixture-duplicate', model: 'fixture-duplicate', protocol: 'chat', baseUrl: 'http://127.0.0.1:1/v1', apiKey: '' }
    await invoke('saveModel', { ...model, id: 'original-aaaaaaaa' })
    await invoke('saveModel', { ...model, id: 'retained-bbbbbbbb' })
    await invoke('updateOnboarding', { hintsHidden: true, cardCollapsed: true })
    const a = await invoke('createProject', { name: '项目甲', parent, brief: '团队隔离', modelId: 'original-aaaaaaaa' })
    const b = await invoke('createProject', { name: '项目乙', parent, brief: '不能被项目甲改动', modelId: 'original-aaaaaaaa' })
    await invoke('setDefaultAssistantModel', 'original-aaaaaaaa')
    const session = await invoke('createAssistantSession', a)
    await invoke('updateAssistantSession', session.id, { modelId: 'original-aaaaaaaa', draft: '保留草稿' })
    await page.getByRole('button', { name: '智能体', exact: true }).click()
    await page.getByRole('heading', { name: '共享智能体模板' }).waitFor()
    assert.equal(await page.locator('.eng-agent-card').count(), 4)
    await capture('shared', 1280, 840)
    await page.getByRole('button', { name: '项目管理', exact: true }).click()
    await page.getByRole('button', { name: '项目甲', exact: true }).click()
    await page.getByRole('button', { name: '项目团队', exact: true }).click()
    await page.getByRole('heading', { name: '项目团队', exact: true }).waitFor()
    assert.equal(await page.locator('.eng-agent-card').count(), 4)
    assert.equal(await page.locator('.eng-agent-card').filter({ hasText: '项目乙' }).count(), 0)
    await capture('project-team', 1280, 840)
    await capture('project-team', 860, 600, 'dark')
    const developer = page.locator('.eng-agent-card').filter({ has: page.getByRole('heading', { name: '全栈开发', exact: true }) })
    await developer.getByRole('button', { name: '配置', exact: true }).click()
    const agentDialog = page.getByRole('dialog', { name: '配置智能体' })
    await agentDialog.locator('input').first().fill('项目甲开发专员')
    await agentDialog.getByRole('button', { name: '保存智能体', exact: true }).click()
    await page.getByRole('heading', { name: '项目甲开发专员' }).waitFor()
    let snapshot = await state()
    assert.equal(snapshot.agents.find(a => a.id === 'developer').name, '全栈开发')
    assert.equal(snapshot.agents.find(a => a.ownerProjectId === b && a.role === 'developer').name, '全栈开发')
    await page.getByRole('combobox', { name: '共享智能体模板' }).selectOption('developer')
    await page.getByRole('button', { name: '复制到项目', exact: true }).click()
    await page.waitForFunction(() => document.querySelectorAll('.eng-agent-card').length === 5)
    snapshot = await state()
    assert.equal(snapshot.projects.find(p => p.id === b).teamAgentIds.length, 4)
    await page.getByRole('button', { name: '模型连接', exact: true }).click()
    await page.locator('.eng-model-card').filter({ hasText: '连接 aaaaaaaa' }).getByRole('button', { name: '删除模型 fixture-duplicate' }).click()
    const dialog = page.getByRole('dialog', { name: '删除模型连接' })
    await dialog.getByRole('button', { name: '迁移绑定并删除' }).waitFor()
    assert.equal(await dialog.getByRole('combobox', { name: '替代模型连接' }).inputValue(), 'retained-bbbbbbbb')
    await capture('model-references', 1280, 840)
    await capture('model-references', 860, 600, 'dark')
    await dialog.getByRole('button', { name: '迁移绑定并删除' }).click()
    await dialog.waitFor({ state: 'hidden' })
    snapshot = await state()
    assert.equal(snapshot.models.length, 1)
    assert.ok(snapshot.agents.every(a => a.modelId === 'retained-bbbbbbbb'))
    assert.equal(snapshot.defaultAssistantModelId, 'retained-bbbbbbbb')
    assert.equal(snapshot.assistant.sessions.find(s => s.id === session.id).draft, '保留草稿')
    await app.close(); app = undefined
    await launch()
    snapshot = await state()
    assert.equal(snapshot.models.length, 1)
    assert.equal(snapshot.agents.filter(agent => agent.ownerProjectId === a).length, 5)
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(output, 'evidence.json'), JSON.stringify({ status: 'passed', checks: ['shared/project separation', 'project edits isolated', 'template copy', 'reference migration and delete', 'restart persistence', '1280x840 and 860x600 dark layouts'], loadingChecks: 'not run per user request', screenshots }, null, 2))
    console.log('PASS isolated Electron team and model management smoke')
  } catch (error) {
    console.error('Renderer errors:', errors)
    if (page) { console.error((await page.locator('body').innerText()).slice(0, 5000)); await page.screenshot({ path: path.join(output, 'failure.png') }) }
    throw error
  } finally { if (app) await app.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
