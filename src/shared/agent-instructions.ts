// One-time upgrade: keep member-specific instructions verbatim and never truncate them.
// Later edits remain independent, including deliberately shorter instructions.
export function upgradeAgentInstructions(agent: AgentConfig) {
  if ((agent.instructionsVersion ?? 0) >= agentInstructionsVersion) return
  const current = agent.instructions.trim(), preset = defaultAgentInstructions[agent.role]
  const expanded = !current || current === preset || legacyInstructions[agent.role].includes(current)
    ? preset
    : `【成员分工与专门要求】\n${agent.instructions}\n\n以下角色规范仅在上述分工和本轮任务范围内适用，不扩大该成员的职责或工具权限。\n\n${preset}`
  if (expanded.length <= 10000) agent.instructions = expanded
  agent.instructionsVersion = agentInstructionsVersion
}
